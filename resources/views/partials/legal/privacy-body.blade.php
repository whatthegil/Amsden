<p>
    This policy explains what personal information C-BAMS collects, why it is collected, and
    how it is handled. It applies to the System operated by the Camarines Sur Polytechnic
    Colleges (&ldquo;CSPC&rdquo;) Library.
  </p>

  <h2>1. Information we collect</h2>

  <h3>Account information</h3>
  <p>
    When your account is created &mdash; by a Library administrator, or automatically on your
    first CSPC Google sign-in &mdash; we store your name, your CSPC institutional email
    address, your assigned role (Administrator, Faculty, or Student), and whether you have
    permission to upload.
  </p>
  <p>
    If you sign in with Google we also store your Google account identifier and the URL of
    your Google profile picture, so that your account can be recognised on later sign-ins. We
    request only your basic profile and email address from Google. We do not receive, and
    cannot access, your Google password.
  </p>

  <h3>Activity records</h3>
  <p>
    The System keeps an audit log of activity carried out under your account. Each entry
    records your name and email address, the action taken, the document involved where
    relevant, and the date and time. Logged actions include:
  </p>
  <ul>
    <li>signing in and signing out;</li>
    <li>viewing, searching, bookmarking, and uploading bluebooks;</li>
    <li>administrative actions such as approving, rejecting, or editing records;</li>
    <li>attempts to reach a page your role is not permitted to open;</li>
    <li>detected attempts to screenshot or screen-record a document page.</li>
  </ul>

  <h3>Content you submit</h3>
  <p>
    Where you upload a document, we store the file, the metadata you supply, and text
    extracted from the document to make it searchable.
  </p>

  <h2>2. Why we collect it</h2>
  <ul>
    <li><strong>To provide the System</strong> &mdash; authenticating you, applying the correct role, and showing your own uploads, history, and bookmarks.</li>
    <li><strong>To protect archived work</strong> &mdash; the audit log deters and evidences misuse of material that belongs to its authors.</li>
    <li><strong>Institutional compliance</strong> &mdash; the Library must be able to account for who accessed which research material.</li>
    <li><strong>To improve discovery</strong> &mdash; extracted text powers search, duplicate-title checking, and literature review results.</li>
  </ul>

  <h2>3. Automated processing</h2>
  <p>
    Uploaded PDFs are processed automatically to extract their text. Where the literature
    review feature is enabled, short extracts of a document&rsquo;s text and metadata may be
    sent to a third-party AI provider to generate summaries of search results. Only bluebook
    content is sent for this purpose &mdash; never your account details or activity log. If
    the feature is disabled, summaries are produced entirely within the System.
  </p>

  <h2>4. Who can see your information</h2>
  <ul>
    <li><strong>You</strong> may view your own profile, uploads, bookmarks, and activity history.</li>
    <li><strong>Library administrators</strong> may view all accounts, all submissions, and the full audit log.</li>
    <li><strong>Other users</strong> see only what is published in the archive: the bluebook record and, for documents you upload, your name as the uploader.</li>
  </ul>
  <p>
    We do not sell your information, and we do not share it with third parties for advertising
    or any other commercial purpose. Information may be disclosed where CSPC is required to do
    so by law or by College disciplinary process.
  </p>

  <h2>5. Screen-capture detection</h2>
  <p>
    When viewing a document, the System applies a watermark and attempts to detect screenshot
    and screen-recording activity in your browser, recording an entry in the audit log when it
    does. This is a deterrent, not a technical prevention: capture at the operating-system
    level cannot be blocked, and the System does not access your screen, camera, files, or any
    other application.
  </p>

  <h2>6. Cookies</h2>
  <p>
    The System sets a session cookie to keep you signed in and a CSRF token cookie to protect
    forms from cross-site request forgery. Both are strictly necessary for the System to work.
    No advertising or third-party tracking cookies are used. Your browser&rsquo;s local storage
    is also used to remember interface preferences, such as whether the sidebar is collapsed.
  </p>

  <h2>7. Retention</h2>
  <p>
    Account records are kept while your account remains active. Audit log entries and archived
    bluebooks are retained as institutional records of the Library. Where an account is
    disabled, its activity records remain in the audit log so that the history of access to
    archived work stays complete.
  </p>

  <h2>8. Your choices</h2>
  <p>
    You may review and correct your name from your profile page, and change your password
    there. Your email address and role are managed by the Library and cannot be changed by you.
    To request correction or removal of information held about you, or withdrawal of a document
    you have submitted, contact the Library using the details below.
  </p>

  <h2>9. Security</h2>
  <p>
    Passwords are stored only as salted hashes and are never readable by staff. Access is
    restricted by role, and the System is served over an encrypted connection. No system can be
    guaranteed completely secure, and you should sign out when using a shared computer.
  </p>

  <h2>10. Changes and contact</h2>
  <p>
    This policy may be updated; the date at the top of the page shows when it was last changed.
    Questions or requests about this policy should be directed to the CSPC Library at
    <a href="mailto:library@cspc.edu.ph">library@cspc.edu.ph</a>, or in person at the CSPC Library.
  </p>
